<?php

namespace Modules\MetaFlows\Models;

use App\Http\Traits\HasUuid;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

class MetaFlow extends Model
{
    use HasFactory, HasUuid, SoftDeletes;

    protected $table = 'meta_flows';

    protected $guarded = [];

    protected $casts = [
        'categories'                  => 'array',
        'google_sheet_mapping'         => 'array',
        'google_sheet_enabled'         => 'boolean',
        'reply_message_enabled'        => 'boolean',
        'interactive_reply_enabled'    => 'boolean',
        'interactive_reply_config'     => 'array',
        'email_notification_enabled'   => 'boolean',
        'email_notification_config'    => 'array',
    ];

    // A flow can receive many responses when contacts complete it
    public function responses()
    {
        return $this->hasMany(MetaFlowResponse::class, 'meta_flow_id', 'id');
    }

    // Parse the flow's asset_content JSON and return all form field definitions.
    // Traverses screens[].layout.children[], unwraps Form containers, and returns
    // [{name, label, type, screen}] for the input component types used in WhatsApp Flows.
    // When the field name is a Meta auto-generated string (e.g. "TextArea_de923b"),
    // the label is derived from the component type instead of the cryptic name.
    public function extractFlowFields(): array
    {
        if (!$this->asset_content) {
            return [];
        }

        $inputTypes = ['TextInput', 'TextArea', 'Dropdown', 'CheckboxGroup', 'RadioButtonsGroup', 'DatePicker'];
        $typeLabels = [
            'TextInput'          => 'Text Input',
            'TextArea'           => 'Text Area',
            'Dropdown'           => 'Dropdown',
            'CheckboxGroup'      => 'Checkbox Group',
            'RadioButtonsGroup'  => 'Radio Group',
            'DatePicker'         => 'Date Picker',
        ];
        // Track how many of each type we've seen for numbering (e.g. "Text Input 2")
        $typeCounts = [];
        $fields     = [];

        try {
            $json    = json_decode($this->asset_content, true);
            $screens = $json['screens'] ?? [];

            foreach ($screens as $screen) {
                $screenId   = $screen['id'] ?? '';
                $screenTitle = $screen['title'] ?? $screenId;
                $children = $screen['layout']['children'] ?? [];

                foreach ($children as $child) {
                    // Unwrap Form containers
                    $items = ($child['type'] === 'Form') ? ($child['children'] ?? []) : [$child];

                    foreach ($items as $item) {
                        $type = $item['type'] ?? '';

                        if (in_array($type, $inputTypes)) {
                            $rawName  = $item['name'] ?? '';
                            $rawLabel = $item['label'] ?? '';

                            // Determine a human-readable label:
                            // 1. Use the component's label if it's not a Meta auto-generated name
                            // 2. Otherwise derive from the component type with a counter
                            $isAutoGenerated = preg_match('/^(TextInput|TextArea|Dropdown|CheckboxGroup|RadioButtonsGroup|DatePicker)_[a-z0-9]+$/i', $rawName)
                                || preg_match('/^screen_\d+_(TextInput|TextArea|Dropdown|CheckboxGroup|RadioButtonsGroup|DatePicker)_\d+$/i', $rawName);

                            if (!empty($rawLabel) && !$isAutoGenerated) {
                                $label = $rawLabel;
                            } else {
                                // Derive from component type with counter
                                $typeCount = ($typeCounts[$type] ?? 0) + 1;
                                $typeCounts[$type] = $typeCount;
                                $label = ($typeLabels[$type] ?? $type) . ' ' . $typeCount;
                            }

                            $fields[] = [
                                'name'  => $rawName,
                                'label' => $label,
                                'type'  => $type,
                                'screen' => $screenTitle,
                            ];
                        }
                    }
                }
            }
        } catch (\Throwable) {
            // Malformed JSON — return empty
        }

        return $fields;
    }

    // Return a paginated list for the given organization, optionally filtered by name
    public function listAll(int $organizationId, ?string $searchTerm)
    {
        return $this->where('organization_id', $organizationId)
            ->whereNull('deleted_at')
            ->when($searchTerm, function ($query) use ($searchTerm) {
                $query->where('name', 'like', '%' . $searchTerm . '%');
            })
            ->withCount(['responses' => fn($q) => $q->whereNotNull('response_json')])
            ->latest()
            ->paginate(10);
    }
}
